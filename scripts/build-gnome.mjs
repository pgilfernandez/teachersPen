import {build} from 'esbuild';
import {mkdir, copyFile, rm} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
const uuid = 'teacherspen@pgilfernandez.github.io';
const out = `dist/gnome/${uuid}`;
await rm(out, {recursive: true, force: true});
await mkdir(path.join(out, 'source'), {recursive: true});
for (const file of ['extension.js', 'drawing.js', 'metadata.json', 'LICENSE.md', 'NOTICE.md', 'BUILDING.md', 'build-model.mjs']) await copyFile(`extensions/gnome/${file}`, `${out}/${file}`);
await build({entryPoints: ['src/model.ts'], outfile: `${out}/model.js`, bundle: true, format: 'esm', platform: 'neutral', target: 'firefox115', banner: {js: '// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 Pablo Gil Fernández. See LICENSE-MIT.txt.'}});
await copyFile('src/model.ts', `${out}/source/model.ts`);
await copyFile('licenses/MIT.txt', `${out}/LICENSE-MIT.txt`);
const archive = path.resolve(`dist/gnome/${uuid}.shell-extension.zip`);
await rm(archive, {force: true});
execFileSync('zip', ['-q', archive, 'metadata.json', 'extension.js', 'drawing.js', 'model.js', 'LICENSE.md', 'NOTICE.md', 'LICENSE-MIT.txt', 'BUILDING.md', 'build-model.mjs', 'source/model.ts'], {cwd: out, stdio: 'inherit'});
console.log(`GNOME extension: dist/gnome/${uuid}.shell-extension.zip`);
